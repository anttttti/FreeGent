describe('shell constructs in combination', () => {
    for (const [name, script, expected] of CASES) {
        it(name, async () => {
            const sh = await getShell();
            const r = await Promise.race([
                sh.exec(script),
                new Promise<never>((_, rej) => setTimeout(() => rej(new Error('did not finish in 10 s')), 10000)),
            ]);
            expect(lf(r.stdout)).toBe(expected);
        }, 15000);
    }
});
